--  서울시 상권분석서비스(추정매출-상권) 2024년 1분기 ~ 2026년 2분기 (서울열린데이터광장 OA-15572, 서울신용보증재단)
--
--  사용법 (SQLite Online · sqliteonline.com)
--   1) 왼쪽 위 메뉴 File -> Open DB 로 data/seoul_sales.db 를 엶 (표 이름 sales, 215,232행)
--   2) 아래 쿼리를 [번호]별로 블록 선택해 하나씩 실행
--   3) 실행 전에 쿼리가 무엇을 세는지 먼저 읽고 결과의 크기를 예측할 것
--
--  주: 당월_매출_금액은 분기 매출(개인 + 법인). 기준_년분기_코드 20251 = 2025년 1분기.
--      2026년은 2분기까지만 있으므로 연 합계를 다른 해와 그대로 비교하지 않음.
--      성별 · 연령 매출은 법인 매출이 빠져 있어서 합해도 총매출보다 작음.
-- =====================================================================


-- [1] 전체 규모: 연도별 매출 · 결제 건수 · 건당 금액 ===================
SELECT 기준_년분기_코드 / 10                         AS 연도,
       COUNT(*)                                      AS 행수,
       COUNT(DISTINCT 상권_코드)                     AS 상권수,
       SUM(당월_매출_금액)                           AS 매출,
       SUM(당월_매출_건수)                           AS 건수,
       ROUND(1.0 * SUM(당월_매출_금액) / SUM(당월_매출_건수)) AS 건당_금액
FROM   sales
GROUP BY 연도;


-- [2] 시간 흐름: 분기별 매출 (조 원) ====================================
SELECT 기준_년분기_코드,
       ROUND(SUM(당월_매출_금액) / 1e12, 2) AS 매출_조
FROM   sales
GROUP BY 기준_년분기_코드
ORDER BY 기준_년분기_코드;


-- [3] 구분별 비교: 2025년 상권 구분별 매출 비중과 상권 하나당 매출 =======
SELECT 상권_구분_코드_명,
       COUNT(DISTINCT 상권_코드)                                   AS 상권수,
       ROUND(100.0 * SUM(당월_매출_금액)
             / (SELECT SUM(당월_매출_금액) FROM sales WHERE 기준_년분기_코드 / 10 = 2025), 1) AS 비중,
       ROUND(SUM(당월_매출_금액) / COUNT(DISTINCT 상권_코드) / 1e8, 1) AS 상권당_억
FROM   sales
WHERE  기준_년분기_코드 / 10 = 2025
GROUP BY 상권_구분_코드_명
ORDER BY 비중 DESC;


-- [4] 업종별 2025년 매출 상위 10개 (조 원) ===============================
SELECT 서비스_업종_코드_명,
       ROUND(SUM(당월_매출_금액) / 1e12, 2) AS 매출_조
FROM   sales
WHERE  기준_년분기_코드 / 10 = 2025
GROUP BY 서비스_업종_코드_명
ORDER BY 매출_조 DESC
LIMIT 10;


-- [5] 분포와 이상값: 2025년 매출 상위 상권 5개 (억 원) =====================
SELECT 상권_코드_명, 상권_구분_코드_명,
       ROUND(SUM(당월_매출_금액) / 1e8) AS 매출_억
FROM   sales
WHERE  기준_년분기_코드 / 10 = 2025
GROUP BY 상권_코드, 상권_코드_명, 상권_구분_코드_명
ORDER BY 매출_억 DESC
LIMIT 5;


-- [6] 커피-음료 업종: 연도별 매출 · 건수 · 건당 금액 =====================
SELECT 기준_년분기_코드 / 10 AS 연도,
       SUM(당월_매출_금액)   AS 매출,
       SUM(당월_매출_건수)   AS 건수,
       ROUND(1.0 * SUM(당월_매출_금액) / SUM(당월_매출_건수)) AS 건당_금액
FROM   sales
WHERE  서비스_업종_코드_명 = '커피-음료'
GROUP BY 연도;
